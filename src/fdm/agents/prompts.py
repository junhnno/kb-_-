def context_block(
    product_block: str,
    persona_block: str,
    grounding: str,
    facts_block: str = "",
    situation: str = "",
) -> str:
    """디베이트·판정에 공통으로 들어가는 컨텍스트.

    `situation`은 **실제로 이루어진 판매 정황**이다(설명 방식, 권유 경위 등).
    조정례 벤치마크의 정답 라벨은 '판매 행위가 적법했는가'를 판정한 것이라,
    이 정보 없이 상품·페르소나만 주면 모델은 '상품이 위험한가'만 보고 답하게 된다
    (실측: 안내 미흡 사례를 상품 위험도로만 판단해 warn을 fail로 올림).
    상품 설계 단계 시뮬레이션에서는 아직 판매 행위가 없으므로 비워 둔다.
    """
    facts = f"\n{facts_block}\n" if facts_block else ""
    sit = f"\n[판매 정황 — 실제로 이루어진 설명·권유 행위]\n{situation}\n" if situation else ""
    return f"""[상품 정의]
{product_block}

[고객 페르소나]
{persona_block}
{facts}{sit}
[검색된 법령·조정사례 근거]
{grounding}
"""


