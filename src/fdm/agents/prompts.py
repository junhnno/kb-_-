# 우려 목록과 판정 라벨을 분리하는 규칙 (근거 검증 레이어와 한 세트).
#
# JUDGE_SYSTEM의 "토론에서 제기된 우려는 누락 없이 옮긴다"는 규칙은 우려 발굴량을
# 살리려고 넣은 것인데(실측: 심판이 회의론자 우려 4종 중 3종을 버려 발굴량이 단발보다 적었다),
# 부작용으로 **우려 목록이 채워지면 라벨이 따라서 warn으로 끌려간다.**
#
# 실측(qwen3:14b, 22건): 같은 모델이 단발로 판정하면 gold=pass를 11/12 맞히는데,
# 디베이트 전문을 앞에 놓으면 2/12로 떨어졌다. 목록과 라벨이 붙어 있는 것이 원인이다.
#
# 그래서 둘을 끊는다. 목록은 그대로 다 채우고(recall 유지), 라벨은 검증을 통과한
# 중대 우려에만 반응하게 한다. "탐지는 넓게, 판정은 검증된 근거로만."
LABEL_DECOUPLING_RULE = """
[가장 중요 — 우려 목록과 적합성 라벨은 별개다]
우려 목록은 빠짐없이 채워라. 그것은 상품기획자가 검토할 항목이지 위반 판정이 아니다.
적합성 라벨은 아래 조건을 **모두** 만족하는 우려가 있을 때만 warn/fail로 준다.
  (1) 코드 검증에서 기각되지 않았다
  (2) 수치나 조항으로 뒷받침된다 (앵커가 있다)
  (3) 판매 정황상 이미 해소되지 않았다
  (4) 심각도가 '중대' 이상이다
위 네 조건을 다 만족하는 우려가 하나도 없으면 **pass다.** 우려를 5개 적었더라도 pass다.
우려의 **개수**는 라벨과 무관하다. 개수가 아니라 검증된 중대성만 본다.

[혼동 금지 — 적합성은 '판매 행위의 적법성'이다]
아래는 모두 적합성 판정의 근거가 **아니다.** 가입의향점수에만 반영하라.
  - 페르소나가 망설이거나 부담스러워한다 → 구매 의사의 문제이지 판매원칙 위반이 아니다
  - 가입의향점수가 낮다 → 상품이 안 팔린다는 뜻이지 부적합하다는 뜻이 아니다
  - 회의론자가 우려를 제기했다 → 역할상 항상 제기한다. 그 자체는 근거가 아니다
  - 상품군에 일반적으로 있는 조항이 존재한다 → 이 페르소나에게 실제 불리해야 근거가 된다
적합성은 "이 사람에게 이렇게 파는 것이 판매원칙을 어겼는가"만 본다.
페르소나가 안 사겠다고 해도, 판매 과정이 적법했다면 pass다.
"""


def judge_system(decouple_label: bool = False) -> str:
    """심판 시스템 프롬프트 + 우려 유형 목록.

    유형 목록을 런타임에 붙이는 이유: concern_taxonomy.json을 고치면
    프롬프트도 자동으로 따라가야 하기 때문이다(두 곳에 적어두면 어긋난다).

    `decouple_label`은 근거 검증 레이어(claim_check.py)와 한 세트다.
    코드가 기각 목록을 넘겨줘도 "우려가 있으면 warn"이라는 연결이 남아 있으면
    효과가 상쇄되므로, 두 개입은 같은 플래그로 함께 켠다.
    """
    from ..concerns import prompt_type_list

    body = JUDGE_SYSTEM + (LABEL_DECOUPLING_RULE if decouple_label else "")
    return body + "\n[우려 유형 목록]\n" + prompt_type_list() + "\n"

